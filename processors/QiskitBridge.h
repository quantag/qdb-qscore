// Python code that QiskitProcessor sends to the Python executor (qdb-decom) for a
// Qiskit program. The program itself is passed base64-encoded and runs unchanged
// (compiled from its own text, so tracebacks and line numbers are the file's), with
// its output kept out of the result. While it runs, every instruction added to a
// QuantumCircuit gets the program line that added it (line tracing of the program
// code only). The circuit to debug is exported with qasm2.dumps and the result is
// that QASM followed by the comment line
//   // qscore-lines: l1,l2,...
// with the program line of every QASM line (0 for declarations). BaseQVM reads and
// removes that line (QASM_LINES_MARKER in PythonProcessor.h). Verified with qiskit 2.5.2.

#pragma once

// Defines _qs_qiskit_debug(src_b64, image_path); QiskitProcessor appends the call
// "code777 = _qs_qiskit_debug(...)".
static const char* const QISKIT_BRIDGE = R"QSPY(# --- Quantag QSCore: Qiskit debug bridge (generated by QiskitProcessor) ---
# The program runs unchanged (compiled from its own text, so line numbers are the
# file's lines). While it runs, every instruction added to a QuantumCircuit gets the
# program line that added it. The circuit to debug is exported with qasm2.dumps; the
# result is the QASM followed by one comment line
#   // qscore-lines: l1,l2,...
# with the program line of every QASM line (0 for declarations).
def _qs_qiskit_debug(_qs_src_b64, _qs_image):
    import base64
    import io
    import re
    import sys
    import weakref
    from qiskit import QuantumCircuit, qasm2

    source = base64.b64decode(_qs_src_b64).decode("utf-8")
    filename = "<qscore-program>"
    code = compile(source, filename, "exec")

    tracked = []  # [circuit weakref or object, lines, created directly by the program]
    current = {"line": 0}

    def ref(circuit):
        try:
            return weakref.ref(circuit)
        except TypeError:
            return lambda: circuit

    original_init = QuantumCircuit.__init__

    def init(self, *args, **kwargs):
        original_init(self, *args, **kwargs)
        caller = sys._getframe(1)
        tracked.append([ref(self), [], caller.f_code.co_filename == filename])

    def sync():
        line = current["line"]
        alive = False
        for entry in tracked:
            circuit = entry[0]()
            if circuit is None:
                continue
            alive = True
            lines = entry[1]
            n = len(circuit.data)
            if n > len(lines):
                lines.extend([line] * (n - len(lines)))
            elif n < len(lines):
                del lines[n:]
        if not alive and len(tracked) > 1000:
            tracked[:] = [e for e in tracked if e[0]() is not None]

    def local_trace(frame, event, arg):
        if event == "line":
            sync()
            current["line"] = frame.f_lineno
        elif event == "return":
            sync()
            caller = frame.f_back
            if caller is not None and caller.f_code.co_filename == filename:
                current["line"] = caller.f_lineno
        return local_trace

    def global_trace(frame, event, arg):
        if frame.f_code.co_filename == filename:
            sync()
            return local_trace
        return None

    namespace = {"__name__": "__main__", "__builtins__": __builtins__}
    saved_stdout = sys.stdout
    QuantumCircuit.__init__ = init
    sys.stdout = io.StringIO()
    sys.settrace(global_trace)
    try:
        exec(code, namespace)
        sync()
    finally:
        sys.settrace(None)
        sys.stdout = saved_stdout
        QuantumCircuit.__init__ = original_init

    # The circuit to debug:
    # 1. the last module variable declared as "name = QuantumCircuit(...)";
    # 2. else the last created circuit held by a module variable;
    # 3. else the largest circuit the program created itself (in a function).
    circuit = None
    for name in reversed(re.findall(r"^([A-Za-z_]\w*)\s*=[^=].*QuantumCircuit", source, re.M)):
        value = namespace.get(name)
        if isinstance(value, QuantumCircuit):
            circuit = value
            break
    if circuit is None:
        held = {id(v) for k, v in namespace.items() if isinstance(v, QuantumCircuit) and not k.startswith("__")}
        for entry in reversed(tracked):
            value = entry[0]()
            if value is not None and id(value) in held:
                circuit = value
                break
    if circuit is None:
        best = 0
        for entry in tracked:
            value = entry[0]()
            if value is not None and entry[2] and len(value.data) > best:
                circuit, best = value, len(value.data)
    if circuit is None:
        raise RuntimeError("QSCore: no QuantumCircuit found in the program")

    lines = []
    for entry in tracked:
        if entry[0]() is circuit:
            lines = entry[1]
            break

    if _qs_image:
        try:
            circuit.draw(output="mpl", filename=_qs_image)
        except Exception as error:
            sys.stderr.write("QSCore: circuit image not drawn: %s\n" % error)

    qasm = qasm2.dumps(circuit)

    # Program line of every QASM line: one QASM line per circuit instruction after
    # the declarations (barriers included, QSCore skips them).
    declaration = re.compile(r"^\s*((OPENQASM|include|qreg|creg|gate|opaque)\b|//|$)")
    qasm_lines = qasm.splitlines()
    result, index = [], 0
    for text in qasm_lines:
        if declaration.match(text):
            result.append(0)
        else:
            result.append(lines[index] if index < len(lines) else 0)
            index += 1
    if index != len(circuit.data) or len(lines) != len(circuit.data):
        sys.stderr.write("QSCore: %d QASM instructions, %d circuit instructions, %d recorded lines; "
                         "source lines not reported\n" % (index, len(circuit.data), len(lines)))
        return qasm
    return qasm.rstrip("\n") + "\n// qscore-lines: " + ",".join(str(n) for n in result) + "\n"
)QSPY";
